use std::io::Cursor;

use tfhe::prelude::*;
use tfhe::{CompressedCiphertextList, CompressedCiphertextListBuilder, FheUint8, FheUint16};

use crate::error::crypto_error;
use crate::table::{EncryptedRow, KeyDomain};
use crate::{EncryptedTable, Error, Evaluator, MAX_ROWS, Result};

const MAGIC: &[u8; 8] = b"FHELAB01";
const HEADER_BYTES: usize = 8 + 16 + 4;
pub(crate) const MAX_IMAGE_BYTES: usize = 64 * 1024 * 1024;

impl Evaluator {
    pub fn compress_table(&self, table: &EncryptedTable) -> Result<Vec<u8>> {
        self.check_domain(table.domain)?;
        self.in_context(|| {
            let mut builder = CompressedCiphertextListBuilder::new();
            for row in &table.rows {
                builder.push(row.age.clone()).push(row.amount.clone());
            }
            let compressed = builder.build().map_err(crypto_error)?;
            let mut bytes = Vec::new();
            bytes.extend_from_slice(MAGIC);
            bytes.extend_from_slice(&self.domain.0);
            bytes.extend_from_slice(&(table.len() as u32).to_le_bytes());
            tfhe::safe_serialization::safe_serialize(
                &compressed,
                &mut bytes,
                (MAX_IMAGE_BYTES - HEADER_BYTES) as u64,
            )
            .map_err(crypto_error)?;
            if bytes.len() > MAX_IMAGE_BYTES {
                return Err(Error::ImageTooLarge {
                    limit: MAX_IMAGE_BYTES,
                });
            }
            Ok(bytes)
        })
    }

    /// Loads a bounded image generated by this locally trusted experiment.
    /// Format and domain checks are not authentication or protection from malicious peers.
    pub fn restore_trusted_image(&self, bytes: &[u8]) -> Result<EncryptedTable> {
        if bytes.len() > MAX_IMAGE_BYTES {
            return Err(Error::ImageTooLarge {
                limit: MAX_IMAGE_BYTES,
            });
        }
        if bytes.len() < HEADER_BYTES || &bytes[..8] != MAGIC {
            return Err(Error::InvalidImage(
                "missing or unsupported format header".into(),
            ));
        }
        let domain = KeyDomain(bytes[8..24].try_into().expect("checked header length"));
        self.check_domain(domain)?;
        let count =
            u32::from_le_bytes(bytes[24..28].try_into().expect("checked header length")) as usize;
        if count > MAX_ROWS {
            return Err(Error::TooManyRows {
                count,
                limit: MAX_ROWS,
            });
        }
        self.in_context(|| {
            let payload = &bytes[HEADER_BYTES..];
            let mut reader = Cursor::new(payload);
            let compressed: CompressedCiphertextList =
                tfhe::safe_serialization::safe_deserialize(&mut reader, MAX_IMAGE_BYTES as u64)
                    .map_err(Error::InvalidImage)?;
            if reader.position() != payload.len() as u64 {
                return Err(Error::InvalidImage("trailing bytes".into()));
            }
            if compressed.len() != count * 2 {
                return Err(Error::InvalidImage(
                    "ciphertext count does not match row count".into(),
                ));
            }
            let mut rows = Vec::with_capacity(count);
            for index in 0..count {
                let age: FheUint8 = compressed
                    .get(index * 2)
                    .map_err(crypto_error)?
                    .ok_or_else(|| Error::InvalidImage("missing age".into()))?;
                let amount: FheUint16 = compressed
                    .get(index * 2 + 1)
                    .map_err(crypto_error)?
                    .ok_or_else(|| Error::InvalidImage("missing amount".into()))?;
                rows.push(EncryptedRow { age, amount });
            }
            Ok(EncryptedTable { domain, rows })
        })
    }
}
