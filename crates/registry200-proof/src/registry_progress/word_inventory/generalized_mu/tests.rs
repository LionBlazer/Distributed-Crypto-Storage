use std::sync::OnceLock;

fn fixed_word() -> &'static RowMajorMatrix<Val> {
    static PP: OnceLock<RowMajorMatrix<Val>> = OnceLock::new();
    PP.get_or_init(|| word_pp().unwrap())
}

fn role3(source: &source::version::SourceVersionExpected) -> encoding::statement::Statement {
    let key = encoding::statement::KeyBinding::new(
        source.statement().heads[0][8..24].try_into().unwrap(),
        [0x73; 16],
        7,
        [0x35; 32],
        source::statement::encode_digest([Val::from_u64(11); 4]),
    )
    .unwrap();
    encoding::statement::Statement {
        expected: encoding::statement::Expected::source_version(source, key).unwrap(),
        encoded: [Val::from_u64(13); 4],
    }
}

/// Complete actual-sized stream without materializing 167MiB of constant PP.
struct Input<'a> {
    prefix: Vec<u8>,
    family: usize,
    position: usize,
    matrix: Option<&'a RowMajorMatrix<Val>>,
    constant: u64,
    damage: Option<(usize, u64)>,
    trailing: bool,
}
impl<'a> Input<'a> {
    fn new(family: usize, public: &[Val], matrix: Option<&'a RowMajorMatrix<Val>>) -> Self {
        assert_eq!(public.len(), PUBLIC[family]);
        let mut prefix = [0; 64].to_vec();
        prefix[..8].copy_from_slice(MAGIC);
        prefix[8] = family as u8;
        prefix[9] = DEPTH[family];
        if PP[family] != 0 {
            prefix[16..48].copy_from_slice(&[0x41; 32]);
            prefix[48..56].copy_from_slice(&19u64.to_le_bytes());
        }
        for value in public {
            prefix.extend(value.as_canonical_u64().to_le_bytes());
        }
        Self {
            prefix,
            family,
            position: 0,
            matrix,
            constant: 7,
            damage: None,
            trailing: false,
        }
    }
    fn extent(&self) -> usize {
        let pp_bytes = if PP[self.family] == 0 {
            0
        } else {
            PP[self.family] * (1usize << DEPTH[self.family]) * 8
        };
        self.prefix.len() + pp_bytes + usize::from(self.trailing)
    }
}
impl Read for Input<'_> {
    fn read(&mut self, output: &mut [u8]) -> io::Result<usize> {
        let count = output.len().min(self.extent() - self.position);
        for (index, byte) in output.iter_mut().take(count).enumerate() {
            let position = self.position + index;
            *byte = if let Some(byte) = self.prefix.get(position) {
                *byte
            } else {
                let at = position - self.prefix.len();
                let cell = at / 8;
                let n = 1usize << DEPTH[self.family];
                let mut value = self.matrix.map_or(self.constant, |matrix| {
                    matrix.values[(cell % n) * PP[self.family] + cell / n].as_canonical_u64()
                });
                if self.damage.is_some_and(|(damaged, _)| damaged == cell) {
                    value = self.damage.unwrap().1;
                }
                // Trailing-byte coverage uses no matrix, so its generated byte
                // is harmless until the strict EOF check rejects it.
                value.to_le_bytes()[at % 8]
            };
        }
        self.position += count;
        Ok(count)
    }
}

#[test]
fn all_five_public_factories_are_associated_before_any_challenge() {
    let source = public_fixture_expected();
    let role3 = role3(&source);
    let publics = [
        source.statement().values(),
        role3.values(),
        vec![Val::from_u64(17); 32],
        vec![Val::from_u64(23); 309],
        vec![-Val::ONE; 32],
    ];
    for (family, public) in publics.iter().enumerate() {
        let matrix = (family == 3).then(fixed_word);
        let mut input = Input::new(family, public, matrix);
        if family == 4 {
            input.constant = Val::ORDER_U64 - 1;
        }
        let result = read_before_first_coin(&mut input).unwrap();
        assert_eq!(result.family, family);
        assert_eq!(&result.public, public);
        assert_eq!(result.columns, PP[family]);
        assert_eq!(result.pp_pin, (PP[family] != 0).then_some(([0x41; 32], 19)));
        assert_eq!(input.position, input.extent());
    }
}

#[test]
fn complete_source_and_role3_profiles_images_tags_keys_and_contexts_are_not_ignored() {
    let source = public_fixture_expected();
    let original = source.statement().values();
    for position in [0, 8, 16, 40, 72, 87, 683] {
        let mut changed = original.clone();
        changed[position] += Val::ONE;
        assert!(
            read_before_first_coin(&mut Input::new(0, &changed, None)).is_err(),
            "{position}"
        );
    }
    let child = role3(&source).values();
    for position in [0, 8, 16, 699, 708, 724, 728] {
        let mut changed = child.clone();
        changed[position] += Val::ONE;
        assert!(
            read_before_first_coin(&mut Input::new(1, &changed, None)).is_err(),
            "{position}"
        );
    }
    // These are legitimate different PUBLIC mathematical claims. The parser
    // derives their coefficients, rather than matching one preselected Expected.
    let mut different_state = original;
    different_state[687] += Val::ONE; // version tag deliberately excludes Cstate
    assert!(read_before_first_coin(&mut Input::new(0, &different_state, None)).is_ok());
    let mut different_cw = child;
    different_cw[736] += Val::ONE; // acyclic Role3 context deliberately excludes Cw
    assert!(read_before_first_coin(&mut Input::new(1, &different_cw, None)).is_ok());
}

#[test]
fn word_requires_every_cell_of_the_genuine_fixed_zero_interleaved_pp() {
    let public = vec![Val::ZERO; 309];
    let mut changed = Input::new(3, &public, Some(fixed_word()));
    let original = fixed_word().values[0].as_canonical_u64();
    changed.damage = Some((0, (original + 1) % Val::ORDER_U64));
    assert_eq!(
        read_before_first_coin(&mut changed).unwrap_err(),
        "Word-PP-differs-from-genuine-fixed-factory"
    );
    // Generalized low-degree zero PP is allowed for DATA/Query, never Word.
    let mut zero = Input::new(3, &public, None);
    zero.constant = 0;
    assert_eq!(
        read_before_first_coin(&mut zero).unwrap_err(),
        "Word-PP-differs-from-genuine-fixed-factory"
    );
}

#[test]
fn fixed_word_polynomial_matches_the_actual_native_public_preprocessing_commitment() {
    use bfv_hiding_stark::Challenge;
    use bfv_hiding_stark::hash::{Challenger, Pcs, config};
    use p3_commit::{Pcs as PcsTrait, UnivariateStarkPcs};
    use p3_field::coset::TwoAdicMultiplicativeCoset;
    use p3_uni_stark::StarkGenericConfig;

    let built = complete_role(true).unwrap();
    let air = ProgramAir {
        plan: Plan::new(built.pool).unwrap(),
    };
    let original = air.preprocessed_trace().unwrap();
    let suite = config().unwrap();
    let pcs = suite.pcs();
    let domain = <Pcs as PcsTrait<Challenge, Challenger>>::natural_domain_for_degree(pcs, 1024);
    // Actual public PCS path performs its own zero interleaving and Merkle
    // commitment. It creates no private trace commitment or proof.
    let (_root, data) = <Pcs as UnivariateStarkPcs<Challenge, Challenger>>::commit_preprocessing(
        pcs,
        [(domain, original)],
    )
    .unwrap();
    let target = TwoAdicMultiplicativeCoset::new(Val::from_u64(7), 13).unwrap();
    let native =
        <Pcs as UnivariateStarkPcs<Challenge, Challenger>>::get_evaluations_on_domain_no_random(
            pcs, &data, 0, target,
        )
        .bit_reverse_rows()
        .to_row_major_matrix();
    assert_eq!((native.height(), native.width()), (8192, 714));
    assert_eq!(native.values, fixed_word().values);
}

#[test]
fn canonical_protocol_bounds_and_actual_query_high_degree_fail_before_coin() {
    let public = vec![Val::ZERO; 32];
    let mut high = Input::new(4, &public, None);
    high.damage = Some((0, 8)); // a point delta has degree32767, not <4096
    assert_eq!(
        read_before_first_coin(&mut high).unwrap_err(),
        "PP-degree-reaches-k"
    );
    for (position, value) in [(8, 5), (9, 14), (10, 1), (56, 1)] {
        let mut bad = Input::new(4, &public, None);
        bad.prefix[position] = value;
        assert!(read_before_first_coin(&mut bad).is_err());
    }
    let mut noncanonical = Input::new(4, &public, None);
    noncanonical.prefix[64..72].copy_from_slice(&Val::ORDER_U64.to_le_bytes());
    assert_eq!(
        read_before_first_coin(&mut noncanonical).unwrap_err(),
        "noncanonical-Gold"
    );
    let mut trailing = Input::new(4, &public, None);
    trailing.trailing = true;
    assert_eq!(
        read_before_first_coin(&mut trailing).unwrap_err(),
        "trailing-input"
    );
    assert!(read_before_first_coin(&mut Cursor::new([0u8; 63])).is_err());
}

/// Optional exact bridge for ignored Python frozen-word requests. It is not
/// counted as an executed cross-language gate unless DCS_MU_REQUEST is set.
#[test]
#[ignore = "requires a complete public request from the frozen-snapshot encoder"]
fn protocol_request_from_first_frozen_snapshot_if_requested() {
    let path =
        std::env::var_os("DCS_MU_REQUEST").expect("DCS_MU_REQUEST must name a public request");
    // The protocol uses 8-byte canonical fields; buffer the file adapter so
    // complete wide PP does not cause one operating-system read per field.
    let mut request =
        std::io::BufReader::with_capacity(64 * 1024, std::fs::File::open(path).unwrap());
    let result = read_before_first_coin(&mut request).unwrap();
    eprintln!(
        "mu_source_association family={} public={} pp={} first_pin={} no_admission=true",
        result.family,
        result.public.len(),
        result.columns,
        result.pp_pin.is_some()
    );
}
