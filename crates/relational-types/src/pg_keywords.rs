#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn categories_match_every_entry_of_the_pinned_public_upstream_fixture() {
        let expected: Vec<_> = include_str!("../tests/fixtures/pg18-kwlist.h")
            .lines()
            .filter_map(|line| line.strip_prefix("PG_KEYWORD(\""))
            .map(|line| {
                let (word, rest) = line.split_once('"').unwrap();
                let fields: Vec<_> = rest.split(',').map(str::trim).collect();
                let class = match fields[2] {
                    "UNRESERVED_KEYWORD" => Category::Unreserved,
                    "RESERVED_KEYWORD" => Category::Reserved,
                    "TYPE_FUNC_NAME_KEYWORD" => Category::TypeFunction,
                    "COL_NAME_KEYWORD" => Category::ColumnName,
                    _ => panic!("Unknown upstream category"),
                };
                (word, class)
            })
            .collect();
        assert_eq!(KEYWORDS, expected);
        assert_eq!(KEYWORDS.len(), 494);
        assert!(KEYWORDS.windows(2).all(|pair| pair[0].0 < pair[1].0));
        assert_eq!(category("not_a_keyword"), None);
        for (word, class) in [
            ("select", Category::Reserved),
            ("between", Category::ColumnName),
            ("authorization", Category::TypeFunction),
            ("abort", Category::Unreserved),
        ] {
            assert_eq!(category(word), Some(class));
        }
    }
}
